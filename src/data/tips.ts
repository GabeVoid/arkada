export function getRandomTip(excludeId?: number): OralHealthTip {
  const pool =
    excludeId !== undefined && ORAL_HEALTH_TIPS.length > 1
      ? ORAL_HEALTH_TIPS.filter((tip) => tip.id !== excludeId)
      : ORAL_HEALTH_TIPS;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex] ?? ORAL_HEALTH_TIPS[0];
}

